"""将受支持的 Redirector 正则规则转换为 Surge URL Rewrite；不生成 sing-box 分流规则。"""
import json
from pathlib import Path
import re

CDN = 'https://cdn.jsdelivr.net/gh/tellok/rulesets@main/rewrites/'


def noncapturing(pattern):
    """排除条件的捕获组不应改变主规则的 $1/$2 编号。"""
    result = []
    escaped = False
    in_class = False
    for i, char in enumerate(pattern):
        if escaped:
            result.append(char)
            escaped = False
        elif char == '\\':
            result.append(char)
            escaped = True
        elif char == '[':
            in_class = True
            result.append(char)
        elif char == ']':
            in_class = False
            result.append(char)
        elif char == '(' and not in_class and pattern[i + 1:i + 2] != '?':
            result.append('(?:')
        else:
            result.append(char)
    return ''.join(result)


def convert(rule):
    if rule.get('disabled'):
        return None
    if rule.get('mode', 'regex') != 'regex':
        raise ValueError('URL Pattern mode needs a separate translator')
    pattern, target = rule['from'], rule['to']
    if '{{' in target or any(c.isspace() for c in pattern + target):
        raise ValueError('pipelines/templates or whitespace need a script, not URL Rewrite')
    if not target.startswith(('https://', 'http://')):
        raise ValueError('redirect target must be an HTTP(S) URL')
    re.compile(pattern, re.I)
    # 当前导出仅使用普通编号捕获；拒绝未转换的命名捕获/反向引用。
    if '(?<' in pattern or re.search(r'\\[1-9]', pattern):
        raise ValueError('named captures/lookbehind/backreferences need review')
    exclusion = rule.get('exclude')
    prefix = ''
    if exclusion:
        re.compile(exclusion, re.I)
        if '(?<' in exclusion or re.search(r'\\[1-9]', exclusion):
            raise ValueError('exclude backreferences/named groups need review')
        excluded = noncapturing(exclusion)
        prefix = '(?!' + (excluded[1:] if excluded.startswith('^') else '[\\s\\S]*?(?:' + excluded + ')') + ')'
    # Redirector 使用首个 exec 捕获组拼接整个目标，不保留匹配以外的 URL 后缀。
    # 扩展按 i 标志匹配；首尾包裹不增加捕获组并消费剩余字符，保持相同行为。
    body = pattern[1:] if pattern.startswith('^') else '[\\s\\S]*?(?:' + pattern + ')'
    converted = '(?i)^' + prefix + '(?:' + body + ')[\\s\\S]*$'
    re.compile(converted)
    return f'{converted} {target} 302'


def mitm_hosts(rules):
    special = {
        '(www.)?hizhan520.com': ['hizhan520.com', 'www.hizhan520.com'],
        '(www.)?(level|south)-plus.net': ['level-plus.net', 'www.level-plus.net', 'south-plus.net', 'www.south-plus.net'],
        'www.sis001.(us)': ['www.sis001.us'],
        '.*.alma6874fe.cc': ['*.alma6874fe.cc'],
    }
    hosts = []
    for rule in rules:
        if rule.get('disabled') or not rule['from'].lstrip('^').startswith('https://'):
            continue
        host = rule['from'].split('://', 1)[1].split('/', 1)[0].replace('\\.', '.')
        candidates = special.get(host, [host])
        for host in candidates:
            if not re.fullmatch(r'(?:\*\.)?[a-zA-Z0-9-]+(?:\.[a-zA-Z0-9-]+)+', host):
                raise ValueError('host pattern requires explicit MITM expansion: ' + host)
            if host not in hosts:
                hosts.append(host)
    return hosts


def render(name, rules):
    lines = [line for rule in rules if (line := convert(rule)) is not None]
    if not lines:
        raise ValueError('no enabled rewrite rules')
    hosts = mitm_hosts(rules)
    text = '\n'.join([
        f'#!MANAGED-CONFIG {CDN}{name}.list interval=86400 strict=false',
        '# Generated by scripts/generate_rewrites.py; edit the companion .redirector.json.',
        '# URL Rewrite fragment, NOT a DOMAIN RULE-SET. HTTPS requires trusted MITM CA.',
        '[URL Rewrite]', *lines, '',
    ])
    module = '\n'.join([
        '#!name=' + name,
        '#!desc=URL redirects; HTTPS requires a trusted CA and the MITM master switch.',
        '[URL Rewrite]', *lines, '', '[MITM]', 'hostname = %APPEND% ' + ','.join(hosts), '',
    ])
    return text, module


def generate(root):
    outputs = {}
    for path in sorted((root / 'rewrites').glob('*.redirector.json')):
        name = path.name.removesuffix('.redirector.json')
        rules = json.loads(path.read_text())
        text, module = render(name, rules)
        outputs[path.with_name(name + '.list')] = text
        outputs[path.with_name(name + '.sgmodule')] = module
    # 全部验证通过后再写入，防止错误源造成部分发布。
    for path, text in outputs.items():
        path.write_text(text)


if __name__ == '__main__':
    generate(Path(__file__).resolve().parents[1])
